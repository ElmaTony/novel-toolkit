// 词组首字索引: 当前字符不是任何词组的首字时直接跳过词表扫描
// （词表 40+ 条，大文件逐字符全表线性扫会明显卡顿）
const _PHRASE_HEADS = new Set(_PHRASES_T2S.map(([p]) => p[0]));

function _convert(text, charMap, phrases) {
  if (!text) return text;
  let result = '';
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (phrases && _PHRASE_HEADS.has(ch)) {
      let matched = false;
      for (const [phrase, replacement] of phrases) {
        if (phrase.length >= 2 && text.startsWith(phrase, i)) {
          result += replacement;
          i += phrase.length;
          matched = true;
          break;
        }
      }
      if (matched) continue;
    }
    result += charMap.get(ch) || ch;
    i++;
  }
  return result;
}

function t2s(text) { return _convert(text, T2S, _PHRASES_T2S); }

